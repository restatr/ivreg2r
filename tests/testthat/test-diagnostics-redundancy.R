test_that("redundancy stat is non-negative", {
  fit <- ivreg2(gril_formula, data = griliches, redundant = "mrt")
  expect_gte(fit$diagnostics$redundancy$stat, 0)
})

test_that("df = K1 * L_tested", {
  # K1=1, L_tested=1 -> df=1
  fit1 <- ivreg2(gril_formula, data = griliches, redundant = "mrt")
  expect_identical(fit1$diagnostics$redundancy$df, 1L)

  # K1=1, L_tested=2 -> df=2
  fit2 <- ivreg2(gril_formula, data = griliches, redundant = c("age", "mrt"))
  expect_identical(fit2$diagnostics$redundancy$df, 2L)
})

test_that("df = K1 * L_tested for multi-endo models", {
  # Inline synthetic dataset (replaces the retired sim_multi_endo fixture data): 2 endogenous regressors, 4 excluded instruments, same shape as the retired test.
  set.seed(20260722)
  n <- 500
  x1 <- rnorm(n)
  x2 <- rnorm(n)
  z1 <- rnorm(n)
  z2 <- rnorm(n)
  z3 <- rnorm(n)
  z4 <- rnorm(n)
  u <- rnorm(n)
  v1 <- rnorm(n)
  v2 <- rnorm(n)
  endo1 <- 0.5 * z1 + 0.3 * z2 + 0.2 * x1 + 0.8 * v1 + 0.3 * u
  endo2 <- 0.4 * z2 + 0.3 * z3 + 0.2 * z4 + 0.1 * x2 + 0.7 * v2 + 0.2 * u
  y <- 1.0 + 0.5 * x1 - 0.3 * x2 + 1.2 * endo1 - 0.8 * endo2 + u
  sim_multi_endo <- data.frame(y, x1, x2, endo1, endo2, z1, z2, z3, z4)

  # K1=2, L_tested=1 -> df=2
  fit1 <- ivreg2(y ~ x1 + x2 | endo1 + endo2 | z1 + z2 + z3 + z4,
                 data = sim_multi_endo, redundant = "z1")
  expect_identical(fit1$diagnostics$redundancy$df, 2L)

  # K1=2, L_tested=2 -> df=4
  fit2 <- ivreg2(y ~ x1 + x2 | endo1 + endo2 | z1 + z2 + z3 + z4,
                 data = sim_multi_endo, redundant = c("z1", "z2"))
  expect_identical(fit2$diagnostics$redundancy$df, 4L)
})

test_that("redundancy suppressed by b0 (no diagnostics)", {
  fit0 <- ivreg2(gril_formula, data = griliches)
  fit <- ivreg2(gril_formula, data = griliches, redundant = "mrt",
                b0 = rep(0, length(coef(fit0))))
  # b0 suppresses all identification diagnostics
  expect_null(fit$diagnostics$redundancy)
})


