#
# compare_redundancy() makes plain assertions (no test_that) so each cell below is one test_that block that skips cleanly if its fixture is missing, reads the fixture once, and fits the model only when the fixture exists — matching the structure of the other re-based families (see test-diagnostics-orthog.R).

compare_redundancy <- function(fit, fixture) {
  red <- fit$diagnostics$redundancy
  expect_false(is.null(red))
  expect_equal(red$stat, fixture$redstat, tolerance = stata_tol$stat)
  expect_equal(red$p, fixture$redp, tolerance = stata_tol$pval)
  expect_identical(red$df, as.integer(fixture$reddf))
}

