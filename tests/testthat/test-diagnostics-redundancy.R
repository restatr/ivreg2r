# ============================================================================
# Tests: Instrument Redundancy Test (Ticket P1)
# ============================================================================
#
# Tests H0: specified excluded instruments are redundant (zero explanatory power for endogenous regressors) conditional on maintained instruments. KP rk LM test of H0: rank=0. Verifies against Stata ivreg2 fixtures (e(redstat), e(redp), e(reddf)).
#
# M-23 fixture re-base (planning/22-spec-matrix.md): this family moved off the Card/sim_multi_endo/ts_hac ad hoc data onto the canonical help-file bases (griliches76, abdata, phillips), generated by tests/stata-benchmarks/generate-redundancy-fixtures.do. `small` is NOT varied in the fixtures themselves — Stata's e(redstat)/e(redp)/e(reddf) are invariant to `small` (see that .do file's header) — so every fixture-comparison cell below fits both small = FALSE and small = TRUE against the same fixture and additionally asserts the two fits agree to machine precision.

# --- Bundled datasets (lazy-loaded with the package) ---
data(griliches, package = "ivreg2r")
data(abdata, package = "ivreg2r")
data(phillips, package = "ivreg2r")
data(mroz, package = "ivreg2r")

gril_formula <- lw ~ s + expr + tenure + rns + smsa + factor(year) |
  iq | age + mrt

phil_formula <- cinf ~ 1 | unem | l(unem, 1:3)


# ============================================================================
# Structural tests (no fixtures) — griliches base model
